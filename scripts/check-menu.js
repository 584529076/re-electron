const Database = require('better-sqlite3');
const db = new Database('D:/re-electron/prompts/prompts.db');
const c = db.prepare("SELECT COUNT(*) as cnt FROM prompt_menu").get();
console.log('total rows:', c.cnt);
const cols = db.prepare("PRAGMA table_info(prompt_menu)").all();
console.log('columns:', cols.map(x => x.name).join(', '));
const tree = db.prepare("SELECT id, category_name, parent_id, pid_list FROM prompt_menu ORDER BY id LIMIT 30").all();
console.log('first 30 by id:');
tree.forEach(r => console.log(`  id=${r.id} parent=${r.parent_id} pid=${r.pid_list || '(null)'} name=${r.category_name}`));
const roots = db.prepare("SELECT id, category_name FROM prompt_menu WHERE parent_id IS NULL ORDER BY id").all();
console.log('roots count:', roots.length);
roots.forEach(r => console.log(`  ROOT: id=${r.id} ${r.category_name}`));
